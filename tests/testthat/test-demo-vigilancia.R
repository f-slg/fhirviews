test_that("la demostracion reconcilia eventos, territorios y meses", {
  zona <- Sys.getenv("TZ", unset = NA_character_)
  on.exit(if (is.na(zona)) Sys.unsetenv("TZ") else Sys.setenv(TZ = zona), add = TRUE)
  Sys.setenv(TZ = "UTC")
  carpeta <- withr_tempfile()
  anterior <- Sys.getenv("FHIRVIEWS_DEMO_SALIDA", unset = NA_character_)
  on.exit(if (is.na(anterior)) Sys.unsetenv("FHIRVIEWS_DEMO_SALIDA") else
    Sys.setenv(FHIRVIEWS_DEMO_SALIDA = anterior), add = TRUE)
  on.exit(unlink(carpeta, recursive = TRUE), add = TRUE)
  Sys.setenv(FHIRVIEWS_DEMO_SALIDA = carpeta)
  script <- system.file("examples", "vigilancia.R", package = "fhirviews")
  expect_output(source(script), "Salida:")
  leer <- function(nombre) utils::read.csv(file.path(carpeta, nombre),
                                          colClasses = "character")
  casos <- leer("casos_confirmados.csv")
  territorio <- leer("resumen_canton.csv")
  meses <- leer("resumen_mensual.csv")
  controles <- leer("controles.csv")
  expect_equal(nrow(casos), 661L)
  expect_true(all(casos$verificacion == "confirmed"))
  expect_true(all(casos$cie10 %in% c("A90", "A91")))
  expect_equal(sum(as.integer(territorio$casos)), nrow(casos))
  expect_equal(sum(as.integer(meses$casos)), nrow(casos))
  expect_equal(as.integer(controles$valor[controles$metrica == "eventos_entrada"]), 755L)
  expect_equal(as.integer(controles$valor[controles$metrica == "eventos_excluidos"]), 94L)
  expect_true(all(nchar(territorio$codigo_dpa) == 4L))
  expect_identical(vista_leer(file.path(carpeta, "vista_notificacion.json"))$resource,
                   "Condition")
  procedencia <- jsonlite::read_json(file.path(carpeta, "procedencia.json"))
  expect_match(procedencia$datos, "FICTICIOS")
  expect_match(procedencia$entrada_md5, "^[a-f0-9]{32}$")
  expect_true(file.exists(file.path(carpeta, "sessionInfo.txt")))
  original <- unname(tools::md5sum(file.path(carpeta, "casos_confirmados.csv")))
  expect_error(source(script), "ya existe")
  expect_identical(unname(tools::md5sum(file.path(carpeta, "casos_confirmados.csv"))),
                   original)
})
